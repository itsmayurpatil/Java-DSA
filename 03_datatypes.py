#data types in python
#01. INTEGERS
#  rules for integers
# 1. integers can be +ve , -ve or 0
# 2. integers can be of any size
# 3. integers use the (int) 


num1 = 10
num2 = -20
num3 = 0

print("num1 is :", num1)
print("num2 is :", num2)
print("num3 is :", num3)

print(type(num1))
print(type(num2))
print(type(num3))


#02. STRINGS

#  rules for strings
# 1. strings are enclosed in single ('...') , double ("...") OR triple ('''...''') quotes
# 2. strings can contain letters, numbers, symbols, spaces
# 3. strings are immutable (cannot be changed after creation)

name1 = "MAYUR PATIL*"
num1 = "10"

print("my name is :", name1)
print("num1 is :", num1)

print(type(name1))
print(type(num1))

#03.FLOATS

#  rules for floats
# 1. floats are numbers with decimal points 
# 2. floats can be +ve , -ve or 0
# 3. floats can be of any size

no1 = 20.5
no2 = -15.75

print("no1 is :", no1)
print("no2 is :", no2)

print(type(no1))
print(type(no2))

#04.B00LEANS/BOOLS

#  rules for booleans
# 1. booleans can be True or False

is_true = True
is_false = False

print("is_true is :", is_true)
print("is_false is :", is_false)

print(type(is_true))
print(type(is_false))


#05. NONE

#  rules for None
# 1. None is a special value that represents the absence of a value
# 2. None is often used to indicate that a variable has no value

no_value = None

print("no_value is :", no_value)

print(type(no_value))